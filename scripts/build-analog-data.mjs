// Bundles the saved Earth analog match files into a module the API can import
// on any runtime, including Cloudflare Workers where there is no filesystem
// and no Python process to ask.
//
//   node scripts/build-analog-data.mjs
//
// Temperature matches ship in the repository. Mineral matches are built from
// the EarthChem export, which is stored in Git LFS: with that file present run
// `python -m backend.earth_mineral_matches` first, then this script.
import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const read = async (path) => {
  try { return JSON.parse(await readFile(new URL(path, root), 'utf8')); } catch { return null; }
};
const collection = (payload) =>
  payload?.type === 'FeatureCollection' && Array.isArray(payload.features) ? payload : null;

const temperature = collection(await read('backend/data/earth_temperature_matches.geojson'));
if (!temperature) throw new Error('backend/data/earth_temperature_matches.geojson is missing or invalid.');
const minerals = collection(await read('backend/data/earth_mineral_matches.geojson'));

const TEMPERATURE_KEYS = ['earth_grid_id', 'earth_sample_id', 'earth_annual_average_kelvin', 'earth_temperature_kelvin',
  'earth_temperature_celsius', 'earth_temperature_period', 'earth_data_period', 'earth_data_source'];
const MINERAL_KEYS = ['earth_sample_id', 'earth_sample_name', 'earth_material', 'earth_mineral_class',
  'earth_best_fit_formula', 'earth_formula_match_percentage', 'earth_formula_match_basis',
  'earth_mineral_chemistry_oxide_wt_percent', 'earth_data_source', 'earth_grid_id'];
const slim = (features, keys) => features
  .filter((f) => f?.geometry?.coordinates?.length >= 2 && f.properties)
  .map((f) => ({
    type: 'Feature',
    geometry: { type: 'Point', coordinates: f.geometry.coordinates.slice(0, 2) },
    properties: Object.fromEntries(keys.filter((k) => f.properties[k] != null).map((k) => [k, f.properties[k]])),
  }));

const body = `// Generated by scripts/build-analog-data.mjs. Do not edit by hand.
export const GENERATED_FROM = ${JSON.stringify({
  temperature: temperature.generated_at ?? null,
  minerals: minerals?.generated_at ?? null,
})};
export const TEMPERATURE_SOURCE = ${JSON.stringify(temperature.source ?? null)};
export const TEMPERATURE = ${JSON.stringify(slim(temperature.features, TEMPERATURE_KEYS))};
export const MINERALS = ${minerals ? JSON.stringify(slim(minerals.features, MINERAL_KEYS)) : 'null'};
`;
await writeFile(new URL('server/analog-data.js', root), body);
console.log(`temperature features: ${temperature.features.length}; mineral features: ${minerals ? minerals.features.length : 'not built'}`);
